#![cfg(feature = "build")]

use regol::{
    Feature, FeatureType, Library, Query, TagValue,
    build::{BuildOptions, build_pbf_with_options},
    source::PagedFile,
};
use std::{collections::BTreeMap, path::Path};

fn typed_tags(feature: Feature<'_, PagedFile>) -> regol::Result<BTreeMap<String, (bool, String)>> {
    feature
        .tags()?
        .map(|tag| {
            let tag = tag?;
            let is_text = matches!(tag.value, TagValue::Text(_));
            Ok((tag.key.into_owned(), (is_text, tag.value.to_string())))
        })
        .collect()
}

#[test]
fn built_features_match_the_geodesk_reference() -> anyhow::Result<()> {
    check_reference(BuildOptions::default())
}

#[test]
fn compact_dictionary_matches_the_same_geodesk_reference() -> anyhow::Result<()> {
    check_reference(BuildOptions {
        compact_dictionary: true,
        ..BuildOptions::default()
    })
}

fn check_reference(options: BuildOptions) -> anyhow::Result<()> {
    // The reference was compiled by GOL Tool 2.0.0 with -w from the exact
    // input below, generated by tools/make_fixture.py --builder.
    let fixtures = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    let temp = tempfile::tempdir()?;
    let output = temp.path().join("built.gol");
    let report = build_pbf_with_options(fixtures.join("builder.osm.pbf"), &output, options)?;
    assert_eq!((report.omitted_ways, report.omitted_members), (1, 3));
    let reference = Library::open(fixtures.join("builder.gol"))?;
    let built = Library::open(output)?;
    let mut expected = BTreeMap::new();
    for f in reference.features() {
        let f = f?;
        expected.insert(f.id(), f);
    }
    for actual in built.features() {
        let actual = actual?;
        let id = actual.id();
        let other = expected.remove(&id).expect("unexpected feature in build");
        assert_eq!(actual.is_area(), other.is_area(), "{id}");
        assert_eq!(actual.bounds()?, other.bounds()?, "{id}");
        assert_eq!(typed_tags(actual)?, typed_tags(other)?, "{id}");
        if actual.kind() == FeatureType::Relation {
            let members = |f: Feature<'_, PagedFile>| -> regol::Result<Vec<_>> {
                f.members()?
                    .map(|m| m.map(|m| (m.feature.id(), m.role.into_owned())))
                    .collect()
            };
            assert_eq!(members(actual)?, members(other)?, "{id}");
        }
    }
    assert!(expected.is_empty());
    for (selector, count) in [
        ("n[geodesk:orphan]", 4),
        ("n[geodesk:duplicate]", 3),
        ("ar[geodesk:missing_members]", 2),
        ("n[width='4.7']", 300),
        ("n[lanes=2]", 300),
    ] {
        let query = Query::parse(selector)?;
        assert_eq!(query.prepare(&reference)?.count()?, count, "{selector}");
        assert_eq!(query.prepare(&built)?.count()?, count, "{selector}");
    }
    // An input tag with a stale count is replaced by the observed count.
    assert_eq!(
        Query::parse("*[geodesk:missing_members=2]")?
            .prepare(&built)?
            .count()?,
        1
    );
    Ok(())
}
